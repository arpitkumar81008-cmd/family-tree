const { onCall, HttpsError } = require('firebase-functions/v2/https');
const { initializeApp, getApps } = require('firebase-admin/app');
const { getFirestore, FieldValue } = require('firebase-admin/firestore');

if (getApps().length === 0) {
  initializeApp();
}

const db = getFirestore();

const RATE_LIMIT_WINDOW_MS = 10 * 60 * 1000; // 10 minutes
const RATE_LIMIT_MAX_ATTEMPTS = 10;

/**
 * Verifies and enforces per-UID rate limiting for share-code redemption attempts.
 */
async function enforceRateLimit(uid) {
  const rateRef = db.collection('_rateLimits').doc(`redeem_${uid}`);
  const now = Date.now();

  await db.runTransaction(async tx => {
    const snap = await tx.get(rateRef);
    const data = snap.exists ? snap.data() : null;
    const windowStart = Number(data?.windowStart || 0);
    const count = Number(data?.count || 0);

    if (now - windowStart < RATE_LIMIT_WINDOW_MS) {
      if (count >= RATE_LIMIT_MAX_ATTEMPTS) {
        throw new HttpsError(
          'resource-exhausted',
          'Too many access code attempts. Please wait a few minutes before trying again.'
        );
      }
      tx.set(rateRef, { windowStart, count: count + 1, updatedAt: now }, { merge: true });
    } else {
      tx.set(rateRef, { windowStart: now, count: 1, updatedAt: now });
    }
  });
}

/**
 * Redeems a private Family Access Code (>= 10 chars, generated by generatePrivateShareToken).
 * Looks up matching shareCode in trees/{treeId}/private/sharing via Admin SDK,
 * and adds the caller's UID to collaboratorUids (editor) or viewerUids (viewer).
 */
exports.redeemShareCode = onCall({ region: 'asia-south1', maxInstances: 10 }, async request => {
  if (!request.auth || !request.auth.uid) {
    throw new HttpsError('unauthenticated', 'Please sign in to redeem a Family Access Code.');
  }

  const uid = request.auth.uid;
  const rawCode = request.data?.code;
  if (typeof rawCode !== 'string') {
    throw new HttpsError('invalid-argument', 'A valid access code string is required.');
  }

  const cleanCode = rawCode.trim().toUpperCase();
  if (cleanCode.length < 10 || cleanCode.length > 32 || !/^[A-Z0-9-]+$/.test(cleanCode)) {
    throw new HttpsError(
      'invalid-argument',
      'Access code must be between 10 and 32 alphanumeric characters.'
    );
  }

  await enforceRateLimit(uid);

  const sharingQuery = await db
    .collectionGroup('private')
    .where('shareCode', '==', cleanCode)
    .limit(5)
    .get();

  const sharingDoc = sharingQuery.docs.find(d => d.id === 'sharing');
  if (!sharingDoc) {
    throw new HttpsError('not-found', 'No family tree found with that access code.');
  }

  const treeRef = sharingDoc.ref.parent.parent;
  if (!treeRef) {
    throw new HttpsError('not-found', 'Tree reference could not be resolved.');
  }

  const treeSnap = await treeRef.get();
  if (!treeSnap.exists) {
    throw new HttpsError('not-found', 'That family tree no longer exists.');
  }

  const treeData = treeSnap.data() || {};
  const sharingData = sharingDoc.data() || {};
  const role = sharingData.shareCodeRole === 'editor' ? 'editor' : 'viewer';

  if (treeData.ownerUid !== uid) {
    if (role === 'editor') {
      await treeRef.update({
        collaboratorUids: FieldValue.arrayUnion(uid),
        updatedAt: FieldValue.serverTimestamp()
      });
    } else {
      await treeRef.update({
        viewerUids: FieldValue.arrayUnion(uid),
        updatedAt: FieldValue.serverTimestamp()
      });
    }
  }

  return {
    treeId: treeRef.id,
    role: treeData.ownerUid === uid ? 'owner' : role
  };
});
